    public function run(): void
    {
        foreach ([...array_keys(self::HEADS), ...self::OTHERS] as $name) {
            Position::firstOrCreate(['name' => $name]);
        }

        $this->writeDuties();
    }

    /**
     * Duties go to the positions that have none, and a position that already has
     * some is left alone: by the time the demo is re-seeded somebody has been in
     * the directory writing a unit's real duties, and those are worth more than
     * the invented ones. One query to find the empty positions and one insert for
     * all of them, because a line per duty would be a hundred and fifty round
     * trips on every fresh seed.
     */
    private function writeDuties(): void
    {
        $empty = Position::doesntHave('duties')
            ->whereIn('name', array_keys(self::DUTIES))
            ->pluck('id', 'name');

        $now = now();
        $rows = [];

        foreach ($empty as $name => $id) {
            foreach (self::DUTIES[$name] as $order => $duty) {
                $rows[] = [
                    'position_id' => $id,
                    'name' => $duty,
                    // Its place in the list above, which is the number the page prints.
                    'order' => $order,
                    'created_at' => $now,
                    'updated_at' => $now,
                ];
            }
        }

        if ($rows !== []) {
            PositionDuty::insert($rows);
        }
    }
